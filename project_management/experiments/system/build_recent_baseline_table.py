#!/usr/bin/env python3
"""Build the two-dataset recent-baseline table from completed runs."""

import csv
import statistics
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
SOURCES = (
    "kdd_resubmit_recent_baselines_etth1_h96.csv",
    "kdd_resubmit_ettm2_h96_gate.csv",
    "kdd_resubmit_h96_all_evidence.csv",
)
DATASETS = ("ETTh1", "ETTm2")
TARGETS = (
    "TimeEmb",
    "TFPS",
    "iTransformer+ORI",
    "iTransformer+TIFO[historical]",
)
DISPLAY = {
    "TimeEmb": "TimeEmb",
    "TFPS": "TFPS",
    "iTransformer+ORI": "iTransformer",
    "iTransformer+TIFO[historical]": "iTransformer+TIFO",
}
SEEDS = (2021, 2022, 2023)


def collect():
    rows = {}
    for source in SOURCES:
        with (RESULTS / source).open(newline="") as handle:
            for row in csv.DictReader(handle):
                if (
                    row["dataset"] in DATASETS
                    and int(row["pred_len"]) == 96
                    and row["method"] in TARGETS
                ):
                    key = (row["dataset"], row["method"], int(row["seed"]))
                    value = (float(row["mse"]), float(row["mae"]))
                    if key in rows and rows[key] != value:
                        raise SystemExit(f"conflicting evidence for {key}: {rows[key]} vs {value}")
                    rows[key] = value
    missing = [
        (dataset, method, seed)
        for dataset in DATASETS
        for method in TARGETS
        for seed in SEEDS
        if (dataset, method, seed) not in rows
    ]
    if missing:
        raise SystemExit("incomplete recent-baseline evidence: " + repr(missing))
    return rows


def mean_std(values):
    return statistics.mean(values), statistics.stdev(values)


def latex_value(value, best):
    number = f"{value[0]:.3f} {{\\small $\\pm$ {value[1]:.3f}}}"
    if best:
        number = "\\textbf{" + number + "}"
    return "\\resubmitchange{" + number + "}"


def main():
    rows = collect()
    summary = {
        (dataset, method): tuple(
            mean_std([rows[(dataset, method, seed)][metric] for seed in SEEDS])
            for metric in (0, 1)
        )
        for dataset in DATASETS
        for method in TARGETS
    }
    md = [
        "# Recent-baseline comparison (verified)",
        "",
        "H=96, seeds 2021--2023. Model-level baselines are compared under the same task protocol.",
        "",
        "| Dataset | Method | MSE mean +/- std | MAE mean +/- std |",
        "|---|---|---:|---:|",
    ]
    tex = [
        "% Generated by build_recent_baseline_table.py; H=96/seeds 2021--2023.",
        "\\begin{tabular}{cc|cc}",
        "\\toprule",
        "Dataset & Method & MSE & MAE " + "\\\\",
        "\\midrule",
    ]
    for dataset_index, dataset in enumerate(DATASETS):
        best_mse = min(summary[(dataset, method)][0][0] for method in TARGETS)
        best_mae = min(summary[(dataset, method)][1][0] for method in TARGETS)
        for method_index, method in enumerate(TARGETS):
            mse, mae = summary[(dataset, method)]
            md.append(
                f"| {dataset} | {DISPLAY[method]} | {mse[0]:.3f} +/- {mse[1]:.3f} | "
                f"{mae[0]:.3f} +/- {mae[1]:.3f} |"
            )
            dataset_cell = f"\\multirow{{4}}{{*}}{{{dataset}}}" if method_index == 0 else ""
            tex.append(
                f"{dataset_cell} & {DISPLAY[method]} & "
                f"{latex_value(mse, mse[0] == best_mse)} & "
                f"{latex_value(mae, mae[0] == best_mae)} \\\\"
            )
        if dataset_index + 1 < len(DATASETS):
            tex.append("\\midrule")
    tex.extend(["\\bottomrule", "\\end{tabular}"])
    (RESULTS / "kdd_resubmit_recent_baselines_verified.md").write_text("\n".join(md) + "\n")
    (RESULTS / "kdd_resubmit_recent_baselines_rows.tex").write_text("\n".join(tex) + "\n")
    print("wrote two-dataset recent-baseline table")


if __name__ == "__main__":
    main()
