#!/usr/bin/env python3
"""Build the narrowly scoped recent-baseline table from completed ETTm2/H96 runs."""

import csv
import statistics
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
SOURCES = (
    "kdd_resubmit_ettm2_h96_gate.csv",
    "kdd_resubmit_h96_all_evidence.csv",
)
TARGETS = (
    "TimeEmb",
    "TFPS",
    "iTransformer+ORI",
    "iTransformer+TIFO[historical]",
)
DISPLAY = {
    "TimeEmb": "TimeEmb",
    "TFPS": "TFPS",
    "iTransformer+ORI": "iTransformer",
    "iTransformer+TIFO[historical]": "iTransformer+TIFO",
}


def collect():
    rows = {}
    for source in SOURCES:
        with (RESULTS / source).open(newline="") as handle:
            for row in csv.DictReader(handle):
                if (
                    row["dataset"] == "ETTm2"
                    and int(row["pred_len"]) == 96
                    and row["method"] in TARGETS
                ):
                    key = (row["method"], int(row["seed"]))
                    value = (float(row["mse"]), float(row["mae"]))
                    if key in rows and rows[key] != value:
                        raise SystemExit(f"conflicting evidence for {key}: {rows[key]} vs {value}")
                    rows[key] = value
    missing = [
        (method, seed) for method in TARGETS for seed in (2021, 2022, 2023)
        if (method, seed) not in rows
    ]
    if missing:
        raise SystemExit("incomplete recent-baseline evidence: " + repr(missing))
    return rows


def mean_std(values):
    return statistics.mean(values), statistics.stdev(values)


def fmt(value, best):
    number = f"{value[0]:.3f} {{\\small $\\pm$ {value[1]:.3f}}}"
    if best:
        number = "\\textbf{" + number + "}"
    return "\\resubmitchange{" + number + "}"


def main():
    rows = collect()
    summary = {
        method: tuple(mean_std([rows[(method, seed)][metric] for seed in (2021, 2022, 2023)]) for metric in (0, 1))
        for method in TARGETS
    }
    best_mse = min(summary[method][0][0] for method in TARGETS)
    best_mae = min(summary[method][1][0] for method in TARGETS)
    md = [
        "# Recent-baseline comparison (verified)",
        "",
        "ETTm2, H=96, three seeds (2021--2023). This is intentionally not a four-horizon average.",
        "",
        "| Method | MSE mean ± std | MAE mean ± std |",
        "|---|---:|---:|",
    ]
    tex = [
        "% Generated by build_recent_baseline_table.py; evidence scope: ETTm2/H=96/three seeds.",
        "\\begin{tabular}{c|cc}",
        "\\toprule",
        "Method & MSE & MAE \\\\",
        "\\midrule",
    ]
    for method in TARGETS:
        mse, mae = summary[method]
        md.append(f"| {DISPLAY[method]} | {mse[0]:.3f} ± {mse[1]:.3f} | {mae[0]:.3f} ± {mae[1]:.3f} |")
        tex.append(
            f"{DISPLAY[method]} & {fmt(mse, mse[0] == best_mse)} & {fmt(mae, mae[0] == best_mae)} \\\\")
    tex.extend(["\\bottomrule", "\\end{tabular}"])
    (RESULTS / "kdd_resubmit_recent_baselines_verified.md").write_text("\n".join(md) + "\n")
    (RESULTS / "kdd_resubmit_recent_baselines_rows.tex").write_text("\n".join(tex) + "\n")
    print("wrote recent-baseline table")


if __name__ == "__main__":
    main()
