#!/usr/bin/env python3
"""Mechanically build the old-paper main-table values from completed runs only."""

import csv
import statistics
from collections import defaultdict
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
OUT_MD = RESULTS / "kdd_resubmit_main_table_verified.md"
OUT_TEX = RESULTS / "kdd_resubmit_main_table_rows.tex"
DATASETS = ("ETTh1", "ETTh2", "ETTm1", "ETTm2", "Electricity", "Traffic", "Weather")
SEEDS = (2021, 2022, 2023)
HORIZONS = (96, 192, 336, 720)

SOURCES = (
    "kdd_resubmit_patchtst_ett_all_horizons.csv",
    "kdd_resubmit_patchtst_ettm2_h96_gate.csv",
    "kdd_resubmit_ettm2_h192_two_backbones_gate.csv",
    "kdd_resubmit_patchtst_ettm2_h336_h720.csv",
    "kdd_resubmit_patchtst_custom_all_horizons.csv",
    "kdd_resubmit_h96_all_evidence.csv",
    "kdd_resubmit_ettm2_h192_two_backbones_gate.csv",
    "kdd_resubmit_itransformer_remaining_horizons.csv",
)


def backbone_and_method(label):
    if label.startswith("PatchTST+"):
        return "PatchTST", "TIFO" if "TIFO" in label else "Ori"
    if label.startswith("iTransformer+"):
        return "iTransformer", "TIFO" if "TIFO" in label else "Ori"
    return None, None


def load_rows():
    rows = {}
    missing_sources = [name for name in SOURCES if not (RESULTS / name).exists()]
    if missing_sources:
        raise SystemExit("missing result sources: " + ", ".join(missing_sources))
    for name in SOURCES:
        with (RESULTS / name).open(newline="") as handle:
            for row in csv.DictReader(handle):
                backbone, method = backbone_and_method(row["method"])
                if backbone is None:
                    continue
                key = (backbone, method, row["dataset"], int(row["pred_len"]), int(row["seed"]))
                value = (float(row["mse"]), float(row["mae"]), row["run_id"])
                if key in rows and rows[key][:2] != value[:2]:
                    raise SystemExit(f"conflicting evidence for {key}: {rows[key]} vs {value}")
                rows[key] = value
    return rows


def summary(rows, backbone, method, dataset):
    seed_values = []
    missing = []
    for seed in SEEDS:
        cells = []
        for horizon in HORIZONS:
            key = (backbone, method, dataset, horizon, seed)
            if key not in rows:
                missing.append(key)
            else:
                cells.append(rows[key][:2])
        if len(cells) == len(HORIZONS):
            seed_values.append(tuple(sum(metric[i] for metric in cells) / len(cells) for i in range(2)))
    if missing:
        formatted = "; ".join(f"{d}/{h}/s{s}" for _, _, d, h, s in missing)
        raise SystemExit(f"incomplete {backbone}+{method}: {formatted}")
    return tuple(
        (statistics.mean(values), statistics.stdev(values))
        for values in zip(*seed_values)
    )


def cell(value, best):
    number = f"{value[0]:.3f} {{\\small $\\pm$ {value[1]:.3f}}}"
    if best:
        number = "\\textbf{" + number + "}"
    return "\\resubmitchange{" + number + "}"


def main():
    rows = load_rows()
    summaries = {
        (backbone, method, dataset): summary(rows, backbone, method, dataset)
        for backbone in ("PatchTST", "iTransformer")
        for method in ("TIFO", "Ori") for dataset in DATASETS
    }
    md = ["# Verified main-table values", "", "Average over H={96,192,336,720}; mean ± sample std over seeds 2021/2022/2023.", "", "| Dataset | PatchTST TIFO | PatchTST Ori | iTransformer TIFO | iTransformer Ori |", "|---|---:|---:|---:|---:|"]
    tex = ["% Generated by build_main_table.py; paste rows into Table 1 without manual transcription."]
    for dataset in DATASETS:
        values = {key: summaries[(key[0], key[1], dataset)] for key in (("PatchTST", "TIFO"), ("PatchTST", "Ori"), ("iTransformer", "TIFO"), ("iTransformer", "Ori"))}
        md.append("| " + dataset + " | " + " | ".join(f"{values[key][0][0]:.3f} ± {values[key][0][1]:.3f} / {values[key][1][0]:.3f} ± {values[key][1][1]:.3f}" for key in values) + " |")
        p_tifo, p_ori, i_tifo, i_ori = (values[key] for key in values)
        tex.append(
            f"{{{dataset}}} & {cell(p_tifo[0], p_tifo[0][0] <= p_ori[0][0])} & {cell(p_tifo[1], p_tifo[1][0] <= p_ori[1][0])} & {cell(p_ori[0], p_ori[0][0] < p_tifo[0][0])} & {cell(p_ori[1], p_ori[1][0] < p_tifo[1][0])} & {cell(i_tifo[0], i_tifo[0][0] <= i_ori[0][0])} & {cell(i_tifo[1], i_tifo[1][0] <= i_ori[1][0])} & {cell(i_ori[0], i_ori[0][0] < i_tifo[0][0])} & {cell(i_ori[1], i_ori[1][0] < i_tifo[1][0])} \\\\"
        )
    OUT_MD.write_text("\n".join(md) + "\n")
    OUT_TEX.write_text("\n".join(tex) + "\n")
    print(f"wrote {OUT_MD} and {OUT_TEX}")


if __name__ == "__main__":
    main()
