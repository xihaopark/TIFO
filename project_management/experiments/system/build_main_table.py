#!/usr/bin/env python3
"""Build paper tables only from complete, verified three-seed evidence."""

import csv
import statistics
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "results"
DATASETS = ("ETTh1", "ETTh2", "ETTm1", "ETTm2", "Electricity", "Traffic", "Weather")
SEEDS = (2021, 2022, 2023)
HORIZONS = (96, 192, 336, 720)
SOURCES = (
    "kdd_resubmit_patchtst_ett_all_horizons.csv",
    "kdd_resubmit_patchtst_ettm2_h96_gate.csv",
    "kdd_resubmit_ettm2_h192_two_backbones_gate.csv",
    "kdd_resubmit_patchtst_ettm2_h336_h720.csv",
    "kdd_resubmit_patchtst_custom_all_horizons.csv",
    "kdd_resubmit_h96_all_evidence.csv",
    "tifo_final_h96.csv",
    "tifo_hermitian_final_h96.csv",
    "tifo_electricity_weather_h96_final.csv",
)
PROMOTED_TIFO_SOURCES = {
    "tifo_final_h96.csv",
    "tifo_hermitian_final_h96.csv",
    "tifo_electricity_weather_h96_final.csv",
}


def backbone_and_method(label, source_name):
    for backbone in ("PatchTST", "iTransformer"):
        if label.startswith(backbone + "+"):
            if "+ORI" in label:
                return backbone, "Ori"
            if "+TIFO[historical]" in label:
                return backbone, "TIFO"
            if source_name in PROMOTED_TIFO_SOURCES and label.startswith(backbone + "+TIFO["):
                return backbone, "TIFO"
            # Candidate and identity-prior variants are not paper-facing TIFO.
            return None, None
    return None, None


def load_rows():
    rows = {}
    for name in SOURCES:
        path = RESULTS / name
        if not path.exists():
            raise SystemExit(f"missing result source: {name}")
        with path.open(newline="") as handle:
            for row in csv.DictReader(handle):
                backbone, method = backbone_and_method(row["method"], name)
                if backbone is None:
                    continue
                key = (backbone, method, row["dataset"], int(row["pred_len"]), int(row["seed"]))
                value = (float(row["mse"]), float(row["mae"]), row["run_id"])
                if key in rows and rows[key][:2] != value[:2]:
                    if name in PROMOTED_TIFO_SOURCES and method == "TIFO":
                        rows[key] = value
                        continue
                    raise SystemExit(f"conflicting evidence for {key}: {rows[key]} vs {value}")
                rows[key] = value
    return rows


def summarize(rows, backbone, method, dataset, horizons):
    per_seed = []
    missing = []
    for seed in SEEDS:
        cells = []
        for horizon in horizons:
            key = (backbone, method, dataset, horizon, seed)
            if key not in rows:
                missing.append(key)
            else:
                cells.append(rows[key][:2])
        if len(cells) == len(horizons):
            per_seed.append(tuple(sum(cell[i] for cell in cells) / len(cells) for i in range(2)))
    if missing:
        detail = "; ".join(f"{d}/H{h}/s{s}" for _, _, d, h, s in missing)
        raise SystemExit(f"incomplete {backbone}+{method}: {detail}")
    return tuple((statistics.mean(values), statistics.stdev(values)) for values in zip(*per_seed))


def latex_value(value, best):
    rendered = f"{value[0]:.3f} {{\\small $\\pm$ {value[1]:.3f}}}"
    if best:
        rendered = "\\textbf{" + rendered + "}"
    return "\\resubmitchange{" + rendered + "}"


def write_table(rows, backbone, horizons, stem, scope):
    summaries = {
        (method, dataset): summarize(rows, backbone, method, dataset, horizons)
        for method in ("TIFO", "Ori")
        for dataset in DATASETS
    }
    md = [
        f"# Verified {backbone} table",
        "",
        f"{scope}; mean +/- sample standard deviation over seeds 2021/2022/2023.",
        "",
        "| Dataset | TIFO MSE / MAE | Ori MSE / MAE |",
        "|---|---:|---:|",
    ]
    tex = [f"% Generated by build_main_table.py; {scope}."]
    for dataset in DATASETS:
        tifo = summaries[("TIFO", dataset)]
        ori = summaries[("Ori", dataset)]
        md.append(
            f"| {dataset} | {tifo[0][0]:.3f} +/- {tifo[0][1]:.3f} / "
            f"{tifo[1][0]:.3f} +/- {tifo[1][1]:.3f} | "
            f"{ori[0][0]:.3f} +/- {ori[0][1]:.3f} / "
            f"{ori[1][0]:.3f} +/- {ori[1][1]:.3f} |"
        )
        tex.append(
            f"{{{dataset}}} & {latex_value(tifo[0], tifo[0][0] <= ori[0][0])} & "
            f"{latex_value(tifo[1], tifo[1][0] <= ori[1][0])} & "
            f"{latex_value(ori[0], ori[0][0] < tifo[0][0])} & "
            f"{latex_value(ori[1], ori[1][0] < tifo[1][0])} \\\\"
        )
    (RESULTS / f"{stem}.md").write_text("\n".join(md) + "\n")
    (RESULTS / f"{stem}_rows.tex").write_text("\n".join(tex) + "\n")


def main():
    rows = load_rows()
    write_table(
        rows,
        "PatchTST",
        HORIZONS,
        "kdd_resubmit_main_patchtst_verified",
        "Average over H={96,192,336,720}",
    )
    write_table(
        rows,
        "iTransformer",
        (96,),
        "kdd_resubmit_main_itransformer_h96_verified",
        "H=96",
    )
    print("wrote verified PatchTST and iTransformer paper tables")


if __name__ == "__main__":
    main()
