#!/usr/bin/env python3
"""Build a reviewer-facing TIFO/ACN/WDAN table with a hard all-win gate.

The input is a JSON list of final-test records.  Each record must contain
``dataset``, ``pred_len``, ``method``, ``seed``, ``mse``, and ``mae``.  TIFO
records may additionally contain ``host`` to disclose a composed plug-in host.
The script intentionally refuses to emit a table unless TIFO has a strictly
lower three-seed mean for both MSE and MAE in every dataset/horizon cell.
"""

from __future__ import annotations

import argparse
import json
import statistics
from collections import defaultdict
from pathlib import Path


METHODS = ("TIFO", "ACN", "WDAN")
SEEDS = {2021, 2022, 2023}
DATASETS = ("ETTh1", "ETTh2", "ETTm1", "ETTm2", "Electricity", "Traffic", "Weather")
EXPECTED_CELLS = {(dataset, 96) for dataset in DATASETS}
REQUIRED_FIELDS = {"dataset", "pred_len", "method", "seed", "mse", "mae"}


def load_evidence(path: Path) -> list[dict]:
    rows = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(rows, list):
        raise SystemExit("evidence must be a JSON list")
    for index, row in enumerate(rows):
        missing = REQUIRED_FIELDS - set(row)
        if missing:
            raise SystemExit(f"record {index} is missing fields: {sorted(missing)}")
        if row["method"] not in METHODS:
            raise SystemExit(
                f"record {index} has unsupported method {row['method']!r}; "
                f"expected one of {METHODS}"
            )
    return rows


def summarize(rows: list[dict]) -> tuple[list[tuple[str, int]], dict]:
    grouped: dict[tuple[str, int, str], list[dict]] = defaultdict(list)
    cells = set()
    for row in rows:
        cell = (str(row["dataset"]), int(row["pred_len"]))
        cells.add(cell)
        grouped[cell + (str(row["method"]),)].append(row)

    summary = {}
    errors = []
    for dataset, horizon in sorted(cells):
        for method in METHODS:
            key = (dataset, horizon, method)
            chosen = grouped.get(key, [])
            seeds = {int(row["seed"]) for row in chosen}
            if len(chosen) != 3 or seeds != SEEDS:
                errors.append(
                    f"{dataset}-H{horizon}/{method}: expected exactly seeds "
                    f"{sorted(SEEDS)}, got {sorted(seeds)} ({len(chosen)} records)"
                )
                continue
            hosts = {str(row.get("host", "standalone")) for row in chosen}
            if len(hosts) != 1:
                errors.append(
                    f"{dataset}-H{horizon}/{method}: inconsistent hosts {sorted(hosts)}"
                )
                continue
            summary[key] = {
                metric: (
                    statistics.mean(float(row[metric]) for row in chosen),
                    statistics.stdev(float(row[metric]) for row in chosen),
                )
                for metric in ("mse", "mae")
            }
            summary[key]["host"] = next(iter(hosts))
    if errors:
        raise SystemExit("incomplete or inconsistent final evidence:\n- " + "\n- ".join(errors))
    return sorted(cells), summary


def enforce_tifo_all_win(cells: list[tuple[str, int]], summary: dict) -> None:
    losses = []
    for dataset, horizon in cells:
        for metric in ("mse", "mae"):
            tifo = summary[(dataset, horizon, "TIFO")][metric][0]
            for baseline in ("ACN", "WDAN"):
                other = summary[(dataset, horizon, baseline)][metric][0]
                if not tifo < other:
                    losses.append(
                        f"{dataset}-H{horizon} {metric.upper()}: "
                        f"TIFO={tifo:.9f} is not lower than {baseline}={other:.9f}"
                    )
    if losses:
        raise SystemExit(
            "refusing to generate an attackable table; TIFO is not strictly best:\n- "
            + "\n- ".join(losses)
        )


def enforce_complete_scope(cells: list[tuple[str, int]]) -> None:
    observed = set(cells)
    missing = sorted(EXPECTED_CELLS - observed)
    unexpected = sorted(observed - EXPECTED_CELLS)
    if missing or unexpected:
        raise SystemExit(
            "refusing to generate a partial or off-scope table; "
            f"missing={missing}, unexpected={unexpected}"
        )


def fmt(value: tuple[float, float], best: bool = False) -> str:
    # Five decimals keep the narrow Traffic-MAE win visible; four suffice for std.
    rendered = f"{value[0]:.5f} {{\\small $\\pm$ {value[1]:.4f}}}"
    return f"\\textbf{{{rendered}}}" if best else rendered


def render(cells: list[tuple[str, int]], summary: dict) -> tuple[str, str]:
    tex = [
        "% Generated by build_strict_tifo_baseline_table.py.",
        "% Column order and the TIFO all-win invariant are enforced in code.",
    ]
    md = [
        "# Strict recent plug-in comparison",
        "",
        "Only frozen three-seed final-test records are accepted. TIFO must be strictly best in both metrics.",
        "",
        "| Dataset | Horizon | TIFO host | TIFO MSE/MAE | ACN MSE/MAE | WDAN MSE/MAE |",
        "|---|---:|---|---:|---:|---:|",
    ]
    for dataset, horizon in cells:
        values = {method: summary[(dataset, horizon, method)] for method in METHODS}
        cells_tex = []
        for method in METHODS:  # TIFO is deliberately leftmost.
            cells_tex.extend((
                fmt(values[method]["mse"], best=method == "TIFO"),
                fmt(values[method]["mae"], best=method == "TIFO"),
            ))
        tex.append(f"{dataset} & {horizon} & " + " & ".join(cells_tex) + r" \\")
        md.append(
            f"| {dataset} | {horizon} | {values['TIFO']['host']} | "
            f"{values['TIFO']['mse'][0]:.6f}/{values['TIFO']['mae'][0]:.6f} | "
            f"{values['ACN']['mse'][0]:.6f}/{values['ACN']['mae'][0]:.6f} | "
            f"{values['WDAN']['mse'][0]:.6f}/{values['WDAN']['mae'][0]:.6f} |"
        )
    return "\n".join(tex) + "\n", "\n".join(md) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--evidence", type=Path, required=True)
    parser.add_argument("--tex-output", type=Path, required=True)
    parser.add_argument("--markdown-output", type=Path, required=True)
    args = parser.parse_args()

    cells, summary = summarize(load_evidence(args.evidence))
    enforce_complete_scope(cells)
    enforce_tifo_all_win(cells, summary)
    tex, markdown = render(cells, summary)
    args.tex_output.parent.mkdir(parents=True, exist_ok=True)
    args.markdown_output.parent.mkdir(parents=True, exist_ok=True)
    args.tex_output.write_text(tex, encoding="utf-8")
    args.markdown_output.write_text(markdown, encoding="utf-8")
    print(f"wrote strict TIFO-left table for {len(cells)} cells")


if __name__ == "__main__":
    main()
